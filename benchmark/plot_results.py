#!/usr/bin/env python3
"""Generate publication-ready plots from the fluid benchmark summary."""

from __future__ import annotations

import argparse
import csv
import os
from pathlib import Path


BACKENDS = ("OpenGL", "CUDA", "Vulkan")
SOLVERS = ("WCSPH", "PCISPH")
MARKERS = {"OpenGL": "o", "CUDA": "s", "Vulkan": "^"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot compute time and speedup from benchmark summary.csv."
    )
    parser.add_argument(
        "--summary",
        type=Path,
        default=Path("benchmark/results/summary.csv"),
        help="summary.csv generated by summarize.py",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("benchmark/results/figures"),
        help="directory for PDF and PNG figures",
    )
    parser.add_argument(
        "--raw",
        type=Path,
        default=Path("benchmark/results/raw_results.csv"),
        help="raw per-frame CSV generated by run_matrix.ps1",
    )
    return parser.parse_args()


def load_rows(summary_path: Path) -> dict[tuple[str, str], list[dict[str, float]]]:
    grouped: dict[tuple[str, str], list[dict[str, float]]] = {}
    with summary_path.open(newline="", encoding="utf-8-sig") as stream:
        reader = csv.DictReader(stream)
        required = {
            "Backend",
            "Solver",
            "Particles",
            "Mean_ms",
            "StdDev_ms",
            "P50_ms",
            "P95_ms",
            "MeanInterop_ms",
            "P95Interop_ms",
            "MeanEndToEnd_ms",
            "P95EndToEnd_ms",
            "MeanDensity",
            "MaxDensityError",
            "RMSDensityError",
            "Speedup",
            "CorrectnessValid",
        }
        missing = required.difference(reader.fieldnames or ())
        if missing:
            raise ValueError(f"summary is missing columns: {sorted(missing)}")

        for row in reader:
            backend = row["Backend"]
            solver = row["Solver"]
            if backend not in BACKENDS or solver not in SOLVERS:
                continue
            if row["CorrectnessValid"].strip().lower() != "true":
                raise ValueError(
                    f"refusing to plot invalid group: {backend}/{solver}/"
                    f"{row['Particles']}"
                )
            grouped.setdefault((solver, backend), []).append(
                {
                    "particles": float(row["Particles"]),
                    "mean": float(row["Mean_ms"]),
                    "stddev": float(row["StdDev_ms"]),
                    "p50": float(row["P50_ms"]),
                    "p95": float(row["P95_ms"]),
                    "interop": float(row["MeanInterop_ms"]),
                    "p95_interop": float(row["P95Interop_ms"]),
                    "end_to_end": float(row["MeanEndToEnd_ms"]),
                    "p95_end_to_end": float(row["P95EndToEnd_ms"]),
                    "mean_density": float(row["MeanDensity"]),
                    "max_density_error": float(row["MaxDensityError"]),
                    "rms_density_error": float(row["RMSDensityError"]),
                    "speedup": float(row["Speedup"]),
                }
            )

    expected = {(solver, backend) for solver in SOLVERS for backend in BACKENDS}
    missing_groups = expected.difference(grouped)
    if missing_groups:
        raise ValueError(f"summary is missing groups: {sorted(missing_groups)}")
    for rows in grouped.values():
        rows.sort(key=lambda item: item["particles"])
    return grouped


def load_raw_distributions(
    raw_path: Path,
    selected_particles: tuple[int, ...] = (10000, 50000),
) -> dict[tuple[str, int, str], list[float]]:
    grouped: dict[tuple[str, int, str], list[float]] = {}
    with raw_path.open(newline="", encoding="utf-8-sig") as stream:
        reader = csv.DictReader(stream)
        required = {
            "Backend",
            "Solver",
            "Particles",
            "SampleValid",
            "Compute_ms",
        }
        missing = required.difference(reader.fieldnames or ())
        if missing:
            raise ValueError(f"raw CSV is missing columns: {sorted(missing)}")
        for row in reader:
            backend = row["Backend"]
            solver = row["Solver"]
            particles = int(row["Particles"])
            if (
                backend not in BACKENDS
                or solver not in SOLVERS
                or particles not in selected_particles
                or row["SampleValid"].strip().lower() not in {"1", "true"}
            ):
                continue
            grouped.setdefault((solver, particles, backend), []).append(
                float(row["Compute_ms"])
            )

    expected = {
        (solver, particles, backend)
        for solver in SOLVERS
        for particles in selected_particles
        for backend in BACKENDS
    }
    missing_groups = expected.difference(grouped)
    if missing_groups:
        raise ValueError(f"raw CSV is missing distribution groups: {sorted(missing_groups)}")
    return grouped


def configure_plotting(cache_dir: Path):
    cache_dir.mkdir(parents=True, exist_ok=True)
    os.environ.setdefault("MPLCONFIGDIR", str(cache_dir.resolve()))

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib import font_manager

    font_family = "DejaVu Sans"
    for font_path in (
        Path("C:/Windows/Fonts/msyh.ttc"),
        Path("C:/Windows/Fonts/simhei.ttf"),
    ):
        if font_path.exists():
            font_manager.fontManager.addfont(font_path)
            font_family = font_manager.FontProperties(fname=font_path).get_name()
            break

    plt.rcParams.update(
        {
            "font.family": "sans-serif",
            "font.sans-serif": [font_family, "DejaVu Sans"],
            "axes.unicode_minus": False,
            "font.size": 9,
            "axes.labelsize": 9,
            "axes.titlesize": 10,
            "legend.fontsize": 8,
            "figure.dpi": 160,
            "savefig.dpi": 300,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
        }
    )
    return plt


def save_figure(figure, output_dir: Path, stem: str) -> None:
    for extension in ("pdf", "png"):
        metadata = None
        if extension == "pdf":
            metadata = {
                "Creator": "Graduation_Project benchmark/plot_results.py",
                "CreationDate": None,
                "ModDate": None,
            }
        figure.savefig(
            output_dir / f"{stem}.{extension}",
            bbox_inches="tight",
            pad_inches=0.04,
            metadata=metadata,
        )


def plot_compute_time(plt, grouped, output_dir: Path) -> None:
    figure, axes = plt.subplots(1, 2, figsize=(7.0, 2.65), sharex=True)
    for axis, solver in zip(axes, SOLVERS, strict=True):
        for backend in BACKENDS:
            rows = grouped[(solver, backend)]
            axis.errorbar(
                [row["particles"] for row in rows],
                [row["mean"] for row in rows],
                yerr=[row["stddev"] for row in rows],
                marker=MARKERS[backend],
                linewidth=1.25,
                markersize=4.0,
                capsize=2.0,
                label=backend,
            )
        axis.set_title(solver)
        axis.set_xscale("log")
        axis.set_yscale("log")
        axis.set_xticks([1000, 5000, 10000, 20000, 50000])
        axis.set_xticklabels(["1k", "5k", "10k", "20k", "50k"])
        axis.set_xlabel("粒子数")
        axis.grid(True, which="major", linewidth=0.45, alpha=0.35)
    axes[0].set_ylabel("GPU计算耗时（ms，对数坐标）")
    axes[0].legend(frameon=False)
    figure.tight_layout(w_pad=1.2)
    save_figure(figure, output_dir, "compute-time-comparison")
    plt.close(figure)


def plot_speedup(plt, grouped, output_dir: Path) -> None:
    figure, axes = plt.subplots(1, 2, figsize=(7.0, 2.55), sharex=True, sharey=True)
    for axis, solver in zip(axes, SOLVERS, strict=True):
        for backend in ("CUDA", "Vulkan"):
            rows = grouped[(solver, backend)]
            axis.plot(
                [row["particles"] for row in rows],
                [row["speedup"] for row in rows],
                marker=MARKERS[backend],
                linewidth=1.25,
                markersize=4.0,
                label=backend,
            )
        axis.axhline(1.0, color="0.35", linewidth=0.8, linestyle="--")
        axis.set_title(solver)
        axis.set_xscale("log")
        axis.set_xticks([1000, 5000, 10000, 20000, 50000])
        axis.set_xticklabels(["1k", "5k", "10k", "20k", "50k"])
        axis.set_xlabel("粒子数")
        axis.grid(True, which="major", linewidth=0.45, alpha=0.35)
    axes[0].set_ylabel("相对OpenGL的加速比")
    axes[0].legend(frameon=False)
    figure.tight_layout(w_pad=1.2)
    save_figure(figure, output_dir, "speedup-comparison")
    plt.close(figure)


def plot_density_consistency(plt, grouped, output_dir: Path) -> None:
    figure, axes = plt.subplots(2, 2, figsize=(7.0, 4.8), sharex="col")
    colors = {"OpenGL": "#0072B2", "CUDA": "#D55E00", "Vulkan": "#009E73"}
    for row_index, solver in enumerate(SOLVERS):
        density_axis = axes[row_index][0]
        deviation_axis = axes[row_index][1]
        baseline = {
            row["particles"]: row["mean_density"]
            for row in grouped[(solver, "OpenGL")]
        }
        for backend in BACKENDS:
            rows = grouped[(solver, backend)]
            density_axis.plot(
                [row["particles"] for row in rows],
                [row["mean_density"] for row in rows],
                marker=MARKERS[backend],
                linewidth=1.25,
                markersize=4.0,
                color=colors[backend],
                label=backend,
            )
        for backend in ("CUDA", "Vulkan"):
            rows = grouped[(solver, backend)]
            deviations = [
                max(
                    abs(row["mean_density"] - baseline[row["particles"]])
                    / max(abs(baseline[row["particles"]]), 1.0e-12)
                    * 100.0,
                    1.0e-7,
                )
                for row in rows
            ]
            deviation_axis.plot(
                [row["particles"] for row in rows],
                deviations,
                marker=MARKERS[backend],
                linewidth=1.25,
                markersize=4.0,
                color=colors[backend],
                label=backend,
            )
        deviation_axis.axhline(
            0.1,
            color="0.35",
            linewidth=0.85,
            linestyle="--",
            label="0.1%正确性门槛",
        )
        density_axis.set_title(f"{solver}：平均密度")
        deviation_axis.set_title(f"{solver}：相对偏差")
        for axis in (density_axis, deviation_axis):
            axis.set_xscale("log")
            axis.set_xticks([1000, 5000, 10000, 20000, 50000])
            axis.set_xticklabels(["1k", "5k", "10k", "20k", "50k"])
            axis.grid(True, which="major", linewidth=0.45, alpha=0.35)
        deviation_axis.set_yscale("log")
        density_axis.set_ylabel("平均密度")
        deviation_axis.set_ylabel("相对OpenGL偏差（%）")
    axes[1][0].set_xlabel("粒子数")
    axes[1][1].set_xlabel("粒子数")
    axes[0][0].legend(frameon=False, ncol=3, loc="best")
    axes[0][1].legend(frameon=False, loc="lower left")
    figure.tight_layout(h_pad=1.1, w_pad=1.2)
    save_figure(figure, output_dir, "density-consistency")
    plt.close(figure)


def plot_scalability(plt, grouped, output_dir: Path) -> None:
    figure, axes = plt.subplots(1, 2, figsize=(7.0, 2.7), sharex=True)
    reference_particles = 10000.0
    for axis, solver in zip(axes, SOLVERS, strict=True):
        for backend in BACKENDS:
            rows = grouped[(solver, backend)]
            axis.loglog(
                [row["particles"] for row in rows],
                [row["mean"] for row in rows],
                marker=MARKERS[backend],
                linewidth=1.25,
                markersize=4.0,
                label=backend,
            )

        baseline_rows = grouped[(solver, "OpenGL")]
        anchor = next(
            row["mean"]
            for row in baseline_rows
            if row["particles"] == reference_particles
        )
        particles = [row["particles"] for row in baseline_rows]
        linear_reference = [
            anchor * particle_count / reference_particles
            for particle_count in particles
        ]
        axis.loglog(
            particles,
            linear_reference,
            color="0.35",
            linewidth=0.9,
            linestyle="--",
            label=r"$O(N)$参考（锚定10k）",
        )
        axis.set_title(solver)
        axis.set_xticks([1000, 5000, 10000, 20000, 50000])
        axis.set_xticklabels(["1k", "5k", "10k", "20k", "50k"])
        axis.set_xlabel("粒子数")
        axis.grid(True, which="major", linewidth=0.45, alpha=0.35)
    axes[0].set_ylabel("GPU计算耗时（ms，双对数坐标）")
    axes[0].legend(frameon=False, loc="upper left")
    figure.tight_layout(w_pad=1.2)
    save_figure(figure, output_dir, "scalability-comparison")
    plt.close(figure)


def plot_cuda_end_to_end_composition(plt, grouped, output_dir: Path) -> None:
    figure, axes = plt.subplots(1, 2, figsize=(7.0, 2.7), sharex=True, sharey=True)
    colors = ("#0072B2", "#D55E00", "#999999")
    labels = ("GPU计算", "CUDA–OpenGL互操作", "其他帧开销")
    for axis, solver in zip(axes, SOLVERS, strict=True):
        rows = grouped[(solver, "CUDA")]
        x_positions = list(range(len(rows)))
        compute_share = [row["mean"] / row["end_to_end"] * 100.0 for row in rows]
        interop_share = [row["interop"] / row["end_to_end"] * 100.0 for row in rows]
        other_share = [
            max(row["end_to_end"] - row["mean"] - row["interop"], 0.0)
            / row["end_to_end"]
            * 100.0
            for row in rows
        ]
        bottoms = [0.0] * len(rows)
        for values, label, color in zip(
            (compute_share, interop_share, other_share), labels, colors, strict=True
        ):
            axis.bar(x_positions, values, bottom=bottoms, width=0.68, label=label,
                     color=color, edgecolor="white", linewidth=0.45)
            bottoms = [bottom + value for bottom, value in zip(bottoms, values, strict=True)]
        for x_position, compute, interop in zip(
            x_positions, compute_share, interop_share, strict=True
        ):
            axis.text(x_position, compute + interop + 1.1, f"{interop:.1f}%",
                      ha="center", va="bottom", fontsize=7)
        axis.set_title(solver)
        axis.set_xticks(x_positions, ["1k", "5k", "10k", "20k", "50k"])
        axis.set_xlabel("粒子数")
        axis.set_ylim(0.0, 106.0)
        axis.grid(axis="y", linewidth=0.45, alpha=0.35)
    axes[0].set_ylabel("端到端平均耗时占比（%）")
    handles, legend_labels = axes[0].get_legend_handles_labels()
    figure.legend(
        handles,
        legend_labels,
        frameon=False,
        loc="lower center",
        bbox_to_anchor=(0.5, -0.01),
        ncol=3,
    )
    figure.tight_layout(w_pad=1.2, rect=(0.0, 0.10, 1.0, 1.0))
    save_figure(figure, output_dir, "cuda-end-to-end-composition")
    plt.close(figure)


def plot_end_to_end_realtime_budget(plt, grouped, output_dir: Path) -> None:
    figure, axes = plt.subplots(1, 2, figsize=(7.0, 2.75), sharex=True)
    for axis, solver in zip(axes, SOLVERS, strict=True):
        for backend in BACKENDS:
            rows = grouped[(solver, backend)]
            x_values = [row["particles"] for row in rows]
            mean_values = [row["end_to_end"] for row in rows]
            p95_values = [row["p95_end_to_end"] for row in rows]
            line = axis.plot(
                x_values,
                mean_values,
                marker=MARKERS[backend],
                linewidth=1.25,
                markersize=4.0,
                label=backend,
            )[0]
            axis.fill_between(x_values, mean_values, p95_values, color=line.get_color(),
                              alpha=0.10)
        axis.axhline(16.67, color="#009E73", linewidth=0.85, linestyle="--",
                     label="60 FPS预算")
        axis.axhline(33.33, color="#D55E00", linewidth=0.85, linestyle=":",
                     label="30 FPS预算")
        axis.set_title(solver)
        axis.set_xscale("log")
        axis.set_yscale("log")
        axis.set_xticks([1000, 5000, 10000, 20000, 50000])
        axis.set_xticklabels(["1k", "5k", "10k", "20k", "50k"])
        axis.set_xlabel("粒子数")
        axis.grid(True, which="major", linewidth=0.45, alpha=0.35)
    axes[0].set_ylabel("端到端帧耗时（ms，对数坐标）")
    axes[0].legend(frameon=False, loc="upper left", ncol=2)
    figure.tight_layout(w_pad=1.2)
    save_figure(figure, output_dir, "end-to-end-realtime-budget")
    plt.close(figure)


def plot_timing_distributions(plt, distributions, output_dir: Path) -> None:
    selected_particles = (10000, 50000)
    figure, axes = plt.subplots(2, 2, figsize=(7.0, 5.1))
    colors = ("#0072B2", "#D55E00", "#009E73")
    for row_index, solver in enumerate(SOLVERS):
        for column_index, particles in enumerate(selected_particles):
            axis = axes[row_index][column_index]
            values = [distributions[(solver, particles, backend)] for backend in BACKENDS]
            boxplot = axis.boxplot(
                values,
                tick_labels=BACKENDS,
                whis=(5, 95),
                showfliers=False,
                patch_artist=True,
                medianprops={"color": "black", "linewidth": 1.0},
                whiskerprops={"linewidth": 0.8},
                capprops={"linewidth": 0.8},
            )
            for patch, color in zip(boxplot["boxes"], colors, strict=True):
                patch.set_facecolor(color)
                patch.set_alpha(0.68)
            axis.set_title(f"{solver}，{particles // 1000}k粒子")
            axis.set_ylabel("GPU计算耗时（ms）")
            axis.grid(axis="y", linewidth=0.45, alpha=0.35)
    figure.tight_layout(h_pad=1.15, w_pad=1.2)
    save_figure(figure, output_dir, "compute-time-distributions")
    plt.close(figure)


def main() -> None:
    args = parse_args()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    grouped = load_rows(args.summary.resolve())
    distributions = load_raw_distributions(args.raw.resolve())
    plt = configure_plotting(output_dir / ".matplotlib-cache")
    plot_compute_time(plt, grouped, output_dir)
    plot_speedup(plt, grouped, output_dir)
    plot_density_consistency(plt, grouped, output_dir)
    plot_scalability(plt, grouped, output_dir)
    plot_cuda_end_to_end_composition(plt, grouped, output_dir)
    plot_end_to_end_realtime_budget(plt, grouped, output_dir)
    plot_timing_distributions(plt, distributions, output_dir)
    print(f"Generated benchmark figures in {output_dir}")


if __name__ == "__main__":
    main()
